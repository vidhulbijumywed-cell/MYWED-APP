import { chromium } from '@playwright/test';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
await page.goto(process.env.MYWED_PREVIEW_URL || 'http://127.0.0.1:3000/');
await page.getByLabel('Email address').fill('demo@mywed.test');
await page.getByLabel('Password',{exact:true}).fill('MyWed-demo-2026!');
await page.getByRole('button',{name:'Log in',exact:true}).click();
await page.getByRole('combobox').selectOption({label:'The Frame Studio · Owner'});
await page.getByRole('heading',{name:'A little clarity. A lot of possibilities.'}).waitFor();
await page.screenshot({path:'/workspace/mywed-preview/dashboard.png',fullPage:true});
await page.locator('.sidebar').getByRole('button',{name:'Clients',exact:true}).click();
await page.getByRole('button',{name:'Open',exact:true}).click();
await page.getByRole('heading',{name:'Mira & Arjun'}).waitFor();
await page.screenshot({path:'/workspace/mywed-preview/client-overview.png',fullPage:true});
await page.locator('.sidebar').getByRole('button',{name:'Calendar',exact:true}).click();
await page.getByLabel('Calendar date').fill('2026-11-15');
await page.screenshot({path:'/workspace/mywed-preview/calendar.png',fullPage:true});
await page.locator('.sidebar').getByRole('button',{name:'Dashboard',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'/workspace/mywed-preview/mobile.png',fullPage:true});
await browser.close();
console.log('Captured live dashboard, client overview, calendar, and mobile screens with fictional data.');
